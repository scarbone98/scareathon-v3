import assert from 'node:assert/strict';
import { newGame, createHero, HERO_IDS } from '../src/pages/WaysideFury/game/sim.ts';
import { applyCoopReward, rollCoopCandy } from '../src/pages/WaysideFury/game/coopRewards.ts';
import { makeSave, restoreSave, progressReport } from '../src/pages/WaysideFury/game/save.ts';
import { mergeSaves } from '../src/pages/WaysideFury/game/cloud.ts';
const host = newGame(), guest = newGame();
host.coop = { role: 'host', seat: 0, remoteHeroes: [], appliedHits: [] };
guest.coop = { role: 'guest', seat: 1, remoteHeroes: [], appliedHits: [] };
const pairs = [];
for (let i = 0; i < 12; i++) {
  const id = `test-kill-${i}`, a = rollCoopCandy(id, 'host', false), b = rollCoopCandy(id, 'guest', false);
  pairs.push([a, b]);
  assert.ok(applyCoopReward(host, { id, kind: 'kill', xp: 28, candy: a }));
  assert.ok(applyCoopReward(guest, { id, kind: 'kill', xp: 28, candy: b }));
}
assert.ok(pairs.some(([a, b]) => a !== b), 'loot is rolled independently per player');
assert.deepEqual(host.character, guest.character, 'every player earns full kill XP');
assert.equal(host.kills, 12); assert.equal(guest.kills, 12);
const clear = { id: 'test-clear', kind: 'checkpoint', xp: 0, candy: 0, areas: ['blast'], rooms: ['blast-7'], bosses: ['blast-watcher'], chapter: 1 };
assert.ok(applyCoopReward(guest, clear));
assert.deepEqual(guest.areas, ['blast']); assert.deepEqual(guest.bosses, ['blast-watcher']);
const report = progressReport(guest), save = makeSave(guest, null, false, report.receipt);
assert.ok(save?.coopRewards.includes('test-clear'));
const loaded = restoreSave(save), before = structuredClone(loaded.character), beforeCandy = loaded.candy;
assert.equal(applyCoopReward(loaded, clear), false, 'reload retains replay receipt');
assert.deepEqual(loaded.character, before); assert.equal(loaded.candy, beforeCandy);
assert.equal(progressReport(loaded, save.lastReported).score, 0, 'old checkpoint progress pays no new tickets');
const bonusBefore = structuredClone(loaded.character);
assert.ok(applyCoopReward(loaded, { ...clear, id: 'test-repeat-clear' }));
assert.notDeepEqual(loaded.character, bonusBefore, 'already-completed area gives bonus XP');
assert.equal(progressReport(loaded, save.lastReported).score % 1000, progressReport(loaded, save.lastReported).score, 'repeat area pays no second area ticket delta');
const second = { ...save, savedAt: save.savedAt + 1, coopRewards: ['second-device-reward'] };
const merged = mergeSaves(save, second);
assert.deepEqual(merged.coopRewards, second.coopRewards, 'receipts travel with the chosen character sheet');
const losing = { ...save, character: { level: 1, xp: 28 }, areas: [], bosses: [], clearedRooms: [], coopRewards: ['discarded-kill'] };
assert.ok(!mergeSaves(losing, second).coopRewards.includes('discarded-kill'), 'discarded XP must not be marked paid');
const downed = newGame(); downed.coop = { role: 'host', seat: 0, remoteHeroes: [], appliedHits: [], downed: true };
downed.character = { level: 1, xp: 70 }; downed.heroes.you.hp = 0;
assert.ok(applyCoopReward(downed, { id: 'downed-level', kind: 'kill', xp: 28, candy: 3 }));
assert.equal(downed.character.level, 2); assert.equal(downed.heroes.you.hp, 0, 'XP cannot bypass teammate revival');
assert.ok(applyCoopReward(downed, { id: 'downed-cache', kind: 'checkpoint', xp: 0, candy: 26, healHp: 35, healKi: 20, power: 1 }));
assert.equal(downed.heroes.you.hp, 0, 'cache tonic cannot bypass teammate revival');
assert.equal(downed.gear.power, 1, 'personal cache gear is applied');
const healthy = newGame(); healthy.heroes.you.hp -= 40; healthy.heroes.you.ki = 0;
assert.ok(applyCoopReward(healthy, { id: 'own-cache', kind: 'checkpoint', xp: 0, candy: 18, healHp: 35, healKi: 20, power: 1 }));
assert.equal(healthy.heroes.you.hp, healthy.heroes.you.maxHp - 5); assert.equal(healthy.heroes.you.ki, 20);
assert.equal(applyCoopReward(healthy, { id: 'own-cache', kind: 'checkpoint', xp: 0, candy: 18, healHp: 35, power: 1 }), false);
assert.equal(healthy.gear.power, 1, 'replayed cache cannot double gear');
const synced = newGame(); synced.character = { level: 20, xp: 0 };
synced.heroes = Object.fromEntries(HERO_IDS.map(id => [id, createHero(id, synced.character, synced.gear)]));
synced.coop = { role: 'guest', seat: 1, remoteHeroes: [], appliedHits: [], syncedLevel: 3 };
const { syncCoopLevel } = await import('../src/pages/WaysideFury/game/sim.ts'); syncCoopLevel(synced);
synced.heroes.you.hp = synced.heroes.you.maxHp / 2;
const personal = makeSave(synced, null);
assert.equal(personal.character.level, 20); assert.equal(personal.heroes.you.level, 20);
assert.equal(personal.heroes.you.hp, personal.heroes.you.maxHp / 2, 'cloud saves retain personal stats and HP percentage');
console.log('Wayside Fury co-op rewards: full per-player XP, instanced candy/tonic/gear, new story/bonus XP, durable deduplication, sheet-consistent receipts, ticket deltas and downed/level-sync saves pass.');
