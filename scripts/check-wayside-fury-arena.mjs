import assert from 'node:assert/strict';
import { newGame, enterScene, idleInput, step, interact, activeHero } from '../src/pages/WaysideFury/game/sim.ts';
import { startArena, finishArena, arenaReceipt, tickArena, prepareArenaPlayer, recordArenaResult } from '../src/pages/WaysideFury/u1/hub/arena.ts';
import { ARENA_WORLD, ARENA_HUB_POINT } from '../src/pages/WaysideFury/u1/hub/arenaWorld.ts';
import { isBlocked } from '../src/pages/WaysideFury/game/world.ts';
import { makeSave, restoreSave, progressReport } from '../src/pages/WaysideFury/game/save.ts';
import { arenaScore, arenaKillsThroughWave } from '../server/shared/waysideFury/u1Arena.js';
const tick = (s, frames) => { for (let n = 0; n < frames; n++) step(s, idleInput(), 1 / 60); };
const s = newGame(); enterScene(s, 'hub'); s.x = ARENA_HUB_POINT.x; s.y = ARENA_HUB_POINT.y;
assert.equal(isBlocked(ARENA_WORLD, 320, 304, 7), false);
interact(s); assert.equal(s.overlay, 'arena');
const hp = activeHero(s).hp = 43, candy = s.candy, xp = s.character.xp, before = progressReport(s).score;
assert.equal(startArena(s), true); assert.equal(s.scene, 'arena'); assert.equal(activeHero(s).hp, activeHero(s).maxHp);
tick(s, 181); assert.equal(s.enemies.length, 5);
for (const e of s.enemies) assert.equal(isBlocked(ARENA_WORLD, e.x, e.y, e.radius), false);
for (const e of s.enemies) e.hp = 0;
tick(s, 1); assert.equal(s.arena.wavesCleared, 1); assert.equal(s.arena.kills, 5); assert.equal(arenaScore(1,5),1500);
tick(s, 121); assert.equal(s.enemies.length, 7); assert.equal(s.arena.modifier, 'Quick feet');
assert.ok(s.enemies[0].speed > 23);
assert.equal(finishArena(s), true); assert.equal(finishArena(s), false);
assert.equal(activeHero(s).hp, hp); assert.equal(s.candy, candy); assert.equal(s.character.xp, xp);
assert.equal(progressReport(s).score, before); assert.equal(s.hubArena.soloBest, 1500); assert.equal(s.hubArena.runs,1);
assert.equal(s.events.filter(e=>e.type==='arena-finish').length,1);
assert.ok(arenaReceipt(s.arena).elapsedMs >= 3000);
const save=makeSave(s,null); assert.equal(save.u1.hub.arena.soloBest,1500); assert.equal(restoreSave(save).hubArena.soloBest,1500);
const running=newGame();enterScene(running,'hub');activeHero(running).hp=37;startArena(running);assert.equal(makeSave(running,null).heroes[running.active].hp,37,'temporary tournament healing is never saved');
const late=newGame();late.arena={...s.arena};recordArenaResult(late);assert.equal(late.hubArena,undefined,'late joiners cannot inherit an earlier tournament result');
const legacy={...save}; delete legacy.u1; assert.deepEqual(restoreSave(legacy).hubArena,{soloBest:0,coopBest:0,runs:0});
const guest=newGame(); enterScene(guest,'hub'); guest.coop={role:'guest',seat:1,remoteHeroes:[],appliedHits:[],playerCount:2};
assert.equal(startArena(guest),false); prepareArenaPlayer(guest); guest.arena={...s.arena,mode:'coop',players:2}; recordArenaResult(guest);recordArenaResult(guest);
assert.equal(guest.hubArena.coopBest,1500);assert.equal(guest.hubArena.runs,1);
const host=newGame(); enterScene(host,'hub');host.coop={role:'host',seat:0,remoteHeroes:[],appliedHits:[],playerCount:2}; startArena(host);tick(host,181);
assert.equal(host.enemies.length,5,'co-op retains the deterministic spawn budget');assert.ok(host.enemies[0].maxHp>32);
host.arena.wavesCleared=4;host.arena.wave=5;host.arena.kills=arenaKillsThroughWave(4);host.arena.spawned=false;host.arena.intermission=0;host.enemies=[];tickArena(host,.02);
assert.equal(host.enemies[0].kind,'boss');
const defeated=newGame();enterScene(defeated,'hub');startArena(defeated);defeated.scene='dead';tickArena(defeated,0);
assert.equal(defeated.scene,'hub');assert.equal(defeated.arena.reason,'defeated');
console.log('Tournament arena: waves, modifiers, host authority, separate scores, vitals restoration and save migration pass.');
